def build_stage1_prompt() -> str:
    """构建 Stage 1 的主题域选择 prompt（System Prompt 部分）"""
    
    # 构建域列表
    domain_lines = []
    for code, info in DOMAIN_DEFINITIONS.items():
        line = f"- **{code}**（{info['name']}）：{info['extract']}"
        if "note" in info:
            line += f"\n  {info['note']}"
        line += f"\n  关键词参考：{info['keywords']}"
        domain_lines.append(line)
    
    domains_text = "\n".join(domain_lines)
    
    prompt = f"""# 角色
你是个人记忆主题域分类专家。你的任务是判断一条记忆涉及哪些主题域。

# 任务
给你一条用户记忆，从下方 16 个主题域中选出 1-3 个最相关的。

# ⚠️ 核心原则：多域标注，不漏不推
- 一条数据可以同时归入多个主题域
- 每个域只提取自己视角的信息，不因其他域也收录而放弃提取
- 只要信息中包含某个域关注的维度，就应该选中该域

# 16 个主题域

{domains_text}

# ⚠️ Anniversary 特别注意
- 仅用于"某个日期是什么纪念日"
- 不用于"某件事发生了"
- "我2021年结婚了" → Family（不是 Anniversary）
- "结婚纪念日是10月15日" → Anniversary + Family

# ⚠️ Finance 特别注意
- 只要信息中出现具体金额/价格/花费/收入，Finance 就应该被选中
- "报考雅思花了248元" → Education + Finance
- "去三亚旅行花了3000" → Travel + Finance

# ⚠️ 间接兴趣信号（重要）
- 如果记忆内容是用户主动提及、拍摄、收藏、分享、点评的客观信息（如展品介绍、餐厅描述、景点信息），说明用户对该领域有关注或兴趣，应归入 Hobby
- "中国北宋汝窑青釉盘的珍稀存世样本" → Hobby（用户关注了这个展品）
- "玉芝兰供应带有现代风格的正宗川菜" → Hobby（用户关注了这家餐厅）
- "这是我上周在博物馆拍的信息牌" → Hobby（用户主动拍摄，反映兴趣）

# 思考步骤
1. 这条记忆的核心内容是什么？
2. 它涉及哪些视角？（钱？关系？健康？教育？...）
3. 对每个可能的域，问：这个域能从中提取有价值的信息吗？
4. 选出 1-3 个域

# 输出格式
先简要思考，然后输出 JSON。**每个域必须有独立的理由**：

选1个：
```json
{{
  "domains": {{
    "Career": "选择该域的理由"
  }}
}}
```

选2个：
```json
{{
  "domains": {{
    "Identity": "选择 Identity 的理由",
    "Housing": "选择 Housing 的理由"
  }}
}}
```

选3个：
```json
{{
  "domains": {{
    "Education": "选择 Education 的理由",
    "Finance": "选择 Finance 的理由",
    "Travel": "选择 Travel 的理由"
  }}
}}
```

domains 的 key 只能是主题域代码（如 Identity、Family、Career 等）。"""
    
    return prompt


def build_stage2_prompt(domain_code: str) -> str:
    """
    构建 Stage 2 的子类选择 prompt（System Prompt 部分）
    """
    domain_data = SUBCATEGORY_DEFINITIONS.get(domain_code)
    if not domain_data:
        raise ValueError(f"未知的主题域: {domain_code}")
    
    domain_name = DOMAIN_DEFINITIONS[domain_code]["name"]
    domain_extract = domain_data["domain_extract"]
    
    sub_lines = []
    for i, sub in enumerate(domain_data["subcategories"], 1):
        sub_lines.append(
            f"{i}. **{sub['name']}**\n"
            f"   核心问题：{sub['question']}\n"
            f"   定义：{sub['definition']}\n"
            f"   示例：「{sub['examples']}」"
        )
    
    subcategories_text = "\n\n".join(sub_lines)
    sub_names = [sub["name"] for sub in domain_data["subcategories"]]
    sub_names_str = "、".join(sub_names)
    
    boundary_text = ""
    boundary_rules = domain_data.get("boundary_rules", [])
    if boundary_rules:
        boundary_text = "\n# 边界澄清\n" + "\n".join(boundary_rules) + "\n"
    
    prompt = f"""# 角色
你是 **{domain_code}（{domain_name}）** 域的子类分类专家。

# 本域视角
{domain_extract}

# 任务
给你一条已确定属于 {domain_code} 域的记忆，判断它在回答哪些子类的核心问题，选出 **1-2个** 匹配的子类。

# {domain_code} 域的子类（共 {len(sub_names)} 个）

{subcategories_text}
{boundary_text}
# 选择规则
1. subcategories 必须从以下选项中选择：{sub_names_str}
2. 用"核心问题"来判断：这条记忆在回答哪个/哪些子类的问题？
3. 大多数情况选 1 个就够了
4. 只有当记忆**确实在回答两个不同的核心问题**时才选 2 个（例如"去日本有出入境章"同时回答了"有过什么旅行"和"有什么出行证件"两个问题）
5. 不要因为"沾边"就多选——必须是记忆中有明确的信息在回答那个核心问题

# 输出格式
先简要思考，然后输出 JSON。**每个子类必须有独立的理由**：

选1个：
```json
{{
  "subcategories": {{
    "子类名称": "选择该子类的理由"
  }}
}}
```

选2个：
```json
{{
  "subcategories": {{
    "子类A": "选择子类A的理由",
    "子类B": "选择子类B的理由"
  }}
}}
```"""
    
    return prompt


